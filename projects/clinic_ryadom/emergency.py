# -*- coding: utf-8 -*-
"""
Экстренный триггер @Clinic_ryadom_bot
Детерминированный слой фильтрации (regex/keyword) ДО вызова LLM.
При срабатывании - фиксированный ответ, персонаж-врач НЕ вызывается.
"""

import re
import logging
from datetime import datetime, timezone

log = logging.getLogger("emergency")

# Версия этого слоя фильтрации (для логов и калибровки)
TRIGGER_VERSION = "1.0.0"

# --- Категории маркеров (стартовый список, расширять по логам) -------------
# Каждая категория: regex + фиксированный ответ

GENERAL_RESPONSE = (
    "⚠️ Похоже, это может быть неотложная ситуация. Я - ИИ-консультант, "
    "я не могу помочь в экстренном случае.\n"
    "Пожалуйста, немедленно позвоните в скорую: 103 или 112.\n"
    "Если ситуация связана с психическим кризисом - бесплатная горячая линия "
    "психологической помощи: 8-800-2000-122 (круглосуточно)."
)

SUICIDE_RESPONSE = (
    "Мне очень жаль, что вам сейчас так тяжело. Ваше состояние важно, "
    "и вы заслуживаете поддержки.\n"
    "Я - ИИ-консультант, я не смогу помочь в этой ситуации так, как вам нужно.\n"
    "Пожалуйста, позвоните на бесплатную горячую линию психологической помощи: "
    "8-800-2000-122 (круглосуточно, анонимно) или 112.\n"
    "Рядом есть люди, которые выслушают и помогут. Вы не одни."
)

# Регексы нормализованы (слова в нижнем регистре для сопоставления)
TRIGGERS = {
    "heart_breath": {
        "regex": r"(боль в груди|давит в груди|не могу дышать|задыхаюсь|посинел[аи]? губы|болит сердце|тяжело дышать)",
        "response": GENERAL_RESPONSE,
        "severity": "high",
    },
    "stroke": {
        "regex": r"(онемел[ао]? половина лица|отнялась рука|отнялась нога|отнял[ао]сь|речь заплетается|внезапно перестал видеть|резко перестал видеть|сильнейшая головная боль|сильная головная боль внезапно)",
        "response": GENERAL_RESPONSE,
        "severity": "high",
    },
    "bleed_trauma": {
        "regex": r"(сильное кровотечение|кровь не останавливается|потерял[а]? сознание|без сознания|сильно идёт кровь|кровотечение не останавливается)",
        "response": GENERAL_RESPONSE,
        "severity": "critical",
    },
    "allergy": {
        "regex": r"(отекает горло|отёк квинке|отёк квинке|анафилаксия|отек горла|не могу глотать из-за отека)",
        "response": GENERAL_RESPONSE,
        "severity": "critical",
    },
    "suicide": {
        "regex": r"(хочу умереть|не хочу жить|покончить с собой|причинить себе вред|свести счёты с жизнью|зачем мне жить|не могу больше жить|убью себя)",
        "response": SUICIDE_RESPONSE,
        "severity": "critical_suicide",
    },
}

# Компилируем регексы один раз
_COMPILED = {k: re.compile(v["regex"], re.IGNORECASE) for k, v in TRIGGERS.items()}


def check_emergency(text: str):
    """
    Проверяет текст на маркеры экстренности.
    Возвращает dict с ключами категории и готовым ответом, либо None.
    Категории проверяются в порядке критичности: сначала суицид/критичное.
    """
    if not text:
        return None
    norm = text.lower()

    # Суицид - отдельная ветка, проверяется в первую очередь
    for key in ("suicide", "bleed_trauma", "allergy", "heart_breath", "stroke"):
        m = _COMPILED[key].search(norm)
        if m:
            return {
                "category": key,
                "match": m.group(0),
                "response": TRIGGERS[key]["response"],
                "severity": TRIGGERS[key]["severity"],
            }
    return None


def log_trigger(user_id, doctor_key, category, matched):
    """
    Логирует срабатывание триггера БЕЗ хранения полного текста сообщения,
    чтобы не плодить риск хранения медицинских ПДн в открытом виде.
    Храним: время, user_id, категорию, длину сообщения, совпавшую фразу.
    Совпавшая фраза - короткий маркер (не личный контент).
    """
    try:
        log.info(
            "EMERGENCY_TRIGGER v=%s at=%s user=%s doctor=%s cat=%s len=%d match=%r",
            TRIGGER_VERSION,
            datetime.now(timezone.utc).isoformat(timespec="seconds"),
            user_id,
            doctor_key,
            category,
            len(matched) if matched else 0,
            matched,  # короткий маркер, не весь текст
        )
    except Exception:
        pass
