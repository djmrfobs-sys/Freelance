#!/usr/bin/env python3
"""Бесшовный мелодичный амбиент-луп для сайта KISELEVY CREO.
Все компоненты синтезируются так, что конец = начало (идеальный цикл).
"""
import numpy as np
import scipy.io.wavfile as wav
import os

SR = 44100
DUR = 24.0            # длина лупа, сек
N = int(SR * DUR)
t = np.arange(N) / SR

# ----------------------------------------------------------------------
# 1) Дрейфующий пэд — мягкие расстроенные синусы с целым числом колебаний
#    (добавляем медленный вибрато, у которого тоже целое число циклов)
# ----------------------------------------------------------------------
def pad():
    out = np.zeros(N)
    # Основные ноты аккорда Am7(add9): A2, C4, E4, G4, B4
    freqs = [110.0, 261.63, 329.63, 392.00, 493.88]
    for i, f in enumerate(freqs):
        # целое число периодов за луп => бесшовно по частоте
        k = round(f * DUR)
        f_int = k / DUR
        # медленный вибрато: целое число циклов вибрато за луп
        v_k = 1  # 1 цикл вибрато за 24с
        v_depth = 1.5 if i > 0 else 0.8
        vib = np.sin(2 * np.pi * v_k / DUR * t) * v_depth
        # амплитудная эволюция: плавное "дыхание", целое число циклов
        amp = 0.5 + 0.5 * np.sin(2 * np.pi * 1 / DUR * t + i * 0.5)
        phase = 2 * np.pi * (f_int * t + (v_depth * v_k / (2 * np.pi * f_int)) * np.sin(2 * np.pi * v_k / DUR * t))
        comp = np.sin(phase)
        # лёгкая расстройка/сатурация для теплоты
        comp = np.tanh(comp * 1.4)
        g = (0.10 + 0.02 * i)
        out += comp * amp * g
    return out

# ----------------------------------------------------------------------
# 2) Нежная мелодия — колокольчики/электро-пиано с экспоненциальным
#    затуханием. Выбираем целое число "тактов", чтобы рисунок повторился.
#    Мелодия целиком затухает к концу лупа => конец плавно в начало.
# ----------------------------------------------------------------------
def melody():
    out = np.zeros(N)
    # Мелодия Am — мягкая, вдохновляющая, 8 нот по полтора такта
    # Используем пентатонику поверх Am для приятного звучания
    notes = [
        (329.63, 0.0),   # E4
        (392.00, 1.5),   # G4
        (440.00, 3.0),   # A4
        (493.88, 4.5),   # B4
        (587.33, 6.0),   # D5
        (523.25, 7.5),   # C5
        (392.00, 9.0),   # G4
        (329.63, 10.5),  # E4
        (293.66, 12.0),  # D4
        (329.63, 13.5),  # E4
        (392.00, 15.0),  # G4
        (440.00, 16.5),  # A4
        (523.25, 18.0),  # C5
        (493.88, 19.5),  # B4
        (440.00, 21.0),  # A4
        (392.00, 22.5),  # G4 — последняя нота, затухает в начало
    ]
    for f, start in notes:
        # длительность ноты — остаток до конца лупа с затуханием
        start_idx = int(start * SR)
        if start_idx >= N:
            continue
        # целое число периодов для бесшовности
        k = round(f * DUR)
        f_int = k / DUR
        seg_len = N - start_idx
        seg_t = np.arange(seg_len) / SR
        # экспоненциальное затухание (колокольчик), к концу лупа почти ноль
        decay = np.exp(-seg_t * 1.5)
        # мягкая атака
        attack = np.minimum(seg_t / 0.02, 1.0)
        tone = np.sin(2 * np.pi * f_int * seg_t)
        # богатая обертоновая структура (теплое электропиано)
        tone += 0.4 * np.sin(2 * np.pi * f_int * 2 * seg_t) * np.exp(-seg_t * 4)
        tone += 0.2 * np.sin(2 * np.pi * f_int * 3 * seg_t) * np.exp(-seg_t * 6)
        out[start_idx:] += tone * decay * attack * 0.16
    return out

# ----------------------------------------------------------------------
# 3) Лёгкий атмосферный "воздух" (мягкий шум с целым циклом модуляции)
# ----------------------------------------------------------------------
def air():
    rng = np.random.default_rng(42)
    noise = rng.standard_normal(N)
    # очень мягкий низкочастотный фильтр через свёртку (скользящее среднее)
    kernel = np.hanning(256)
    kernel /= kernel.sum()
    # FFT-фильтрация для корректности
    spec = np.fft.rfft(noise)
    freqs = np.fft.rfftfreq(N, 1 / SR)
    lp = 1 / (1 + (freqs / 800.0) ** 4)   # lowpass ~800 Hz
    noise_f = np.fft.irfft(spec * lp, N)
    # медленная модуляция с целым циклом => бесшовно
    mod = 0.5 + 0.5 * np.sin(2 * np.pi * 2 / DUR * t)
    return noise_f * mod * 0.05

# ----------------------------------------------------------------------
# Сборка + финальный кроссфейд-контроль бесшовности
# ----------------------------------------------------------------------
pad_s = pad()
mel_s = melody()
air_s = air()
mix = pad_s + mel_s + air_s

# Нормализация
mix = mix / (np.max(np.abs(mix)) + 1e-9)
mix *= 0.85

# Финальная огибающая: плавный 1.5с фейд-ин и фейд-аут на СТЫКЕ,
# чтобы гарантировать нулевой шов при loop. Начало и конец совпадают.
fade = int(1.2 * SR)
env = np.ones(N)
env[:fade] = np.linspace(0, 1, fade)
env[-fade:] = np.linspace(1, 0, fade)
# замыкаем: конец плавно уходит в ноль, начало плавно приходит из нуля
# => при пересечении стыка слышно "вдох", бесшовный цикл
mix = mix * env

data = (mix * 32767).astype(np.int16)
out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "11_ambient_melody_loop.wav")
wav.write(out_path, SR, data)
print("WAV written:", out_path, SR, "Hz,", DUR, "s")
