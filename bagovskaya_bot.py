def is_greeting(text):
    t = text.lower().strip()
    greets = ("привет", "здравств", "добрый", "хай", "hello", "здорова", "ку", "доброго")
    return any(t.startswith(g) or t == g for g in greets) and len(text) < 25


def get_next_fact(st):
    """Возвращает следующий проактивный факт, который ещё не рассказывали."""
    idx = st.get("proactive_idx", 0)
    if idx >= len(PROACTIVE):
        return None
    fact = PROACTIVE[idx]
    st["proactive_idx"] = idx + 1
    return fact


def ready_to_view(text):
    """Клиент готов договориться о просмотре."""
    t = text.lower()
    # Если просят фото/информацию - это НЕ просмотр, это запрос контента.
    # Просьба про фото должна идти в базу знаний, а не перехватываться как
    # готовность к визиту. Поэтому "фото/покажи больше/скинь" = False.
    if "фото" in t or "покажи" in t or "скинь" in t or "фотограф" in t:
        return False
    signals = [
        "хочу посмотр", "хочу заехать", "хочу снять", "хочу арендовать",
        "готов снять", "готов посмотреть", "давайте посмотрим", "договоримся",
        "как связаться", "контакт хозяин", "номер хозяин", "дайте номер",
        "дайте контакт", "позвон", "беру дом", "снимаю дом", "оформл",
        "запишите меня", "хотим снять", "когда можно приехать"
    ]
    # Свободно ловим "просмотр/посмотр" (клиенты пишут с опечатками:
    # "когда можно посмотреть", "хочу просмотр", "как псомтреть").
    # Плюс "заехать" ("хотим заехать", "можно заехать на просмотр") - явный
    # сигнал готовности. Но просьбы про фото/на месяц отсекли выше.
    if "посмотр" in t or "просмотр" in t or "заехат" in t or "псоом" in t:
        return True
    return any(s in t for s in signals)


