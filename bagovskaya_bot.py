async def done(update: Update, context: ContextTypes.DEFAULT_TYPE):
    if update.effective_user.id != OWNER_CHAT_ID:
        return
    if not open_leads:
        await update.message.reply_text("Необработанных лидов нет. 🎉")
        return
    open_leads.clear()
    await update.message.reply_text("Готово! Все лиды закрыты, напоминания прекращены.")


async def close_callback(update: Update, context: ContextTypes.DEFAULT_TYPE):
    query = update.callback_query
    if query.from_user.id != OWNER_CHAT_ID:
        await query.answer("Кнопка только для владельца.")
        return
    await query.answer()
    open_leads.clear()
    await query.edit_message_text("✅ Готово! Все лиды обработаны, напоминания прекращены.")


